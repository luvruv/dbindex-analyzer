"""Report generation module for DbIndex Analyzer.

This module formats index recommendations and outputs them into:
1. An executable SQL script (`.sql`) containing commented `CREATE INDEX` statements.
2. A clean, styled HTML report (`.html`) featuring summary metrics, a recommendation table,
   and a one-click clipboard copy button for the SQL commands.
"""

# ------------------------------------------------------------------------------
# Package / Library Imports:
# ------------------------------------------------------------------------------
# html:
# Python's built-in module for handling HTML entities.
# html.escape() converts special characters (like <, >, &, ", ') into safe HTML entities,
# preventing malformed HTML rendering and protecting against HTML/script injection.
import html

# datetime:
# Python's standard library for date and time handling.
# Used here to timestamp the generated HTML report with the exact creation time.
from datetime import datetime


def write_sql_file(suggestions, path):
    """Write recommended CREATE INDEX SQL statements to a file.

    Parameters:
    -----------
    suggestions : list[Suggestion]
        List of Suggestion objects containing recommended indexes and explanations.
    path : str
        File system path where the .sql file should be saved (e.g. "recommendations.sql").

    Returns:
    --------
    None
    """
    # Open the output file with UTF-8 encoding to support all character sets safely
    with open(path, "w", encoding="utf-8") as f:
        f.write("-- Generated by DbIndex Analyzer\n\n")
        for s in suggestions:
            # Include an explanatory comment above each CREATE INDEX command
            # so the database administrator knows why the index was suggested.
            f.write(f"-- {s.table}.{s.column}: {s.reason}\n{s.sql}\n\n")


def write_html_report(db_name, table_count, column_count, suggestions, path):
    """Generate a responsive HTML summary report of the analysis.

    Parameters:
    -----------
    db_name : str
        The name of the database that was analyzed.
    table_count : int
        Total number of user tables scanned.
    column_count : int
        Total number of columns inspected across all tables.
    suggestions : list[Suggestion]
        List of Suggestion objects recommended by the rules engine.
    path : str
        File system path where the .html file should be saved (e.g. "report.html").

    Returns:
    --------
    None
    """
    esc = html.escape  # Alias for concise HTML escaping

    # Build the HTML table rows dynamically from suggestions
    rows = "".join(
        f"<tr><td>{esc(s.table)}.{esc(s.column)}</td><td>{esc(s.reason)}</td>"
        f"<td>{esc(s.speedup)}</td><td><code>{esc(s.sql)}</code></td></tr>"
        for s in suggestions
    )

    # Combine all SQL statements for the copyable textarea block
    all_sql = esc("\n".join(s.sql for s in suggestions))

    # Construct the full HTML document string
    page = f"""<!DOCTYPE html>
<html><head><meta charset="utf-8"><title>DbIndex Report - {esc(db_name)}</title>
<style>
body{{font-family:Arial,sans-serif;margin:30px;color:#222}}
h1{{color:#1a4d8f}}
.cards{{display:flex;gap:16px;margin:20px 0}}
.card{{background:#f0f5fb;padding:14px 22px;border-radius:8px}}
.card b{{font-size:24px;display:block}}
table{{border-collapse:collapse;width:100%}}
th,td{{border:1px solid #ccc;padding:8px;text-align:left;vertical-align:top}}
th{{background:#1a4d8f;color:#fff}}
code,textarea{{font-family:Consolas,monospace;font-size:13px}}
textarea{{width:100%;height:180px}}
button{{padding:8px 16px;margin:8px 0;cursor:pointer}}
</style></head><body>
<h1>DbIndex Analyzer Report</h1>
<p>Database: <b>{esc(db_name)}</b> | Generated: {datetime.now():%Y-%m-%d %H:%M}</p>
<div class="cards">
<div class="card"><b>{table_count}</b>Tables analyzed</div>
<div class="card"><b>{column_count}</b>Columns scanned</div>
<div class="card"><b>{len(suggestions)}</b>Recommendations</div>
</div>
<h2>Recommendations</h2>
<table><tr><th>Column</th><th>Why</th><th>Expected speedup</th><th>SQL</th></tr>{rows}</table>
<h2>All SQL (ready to copy)</h2>
<textarea id="sql" readonly>{all_sql}</textarea><br>
<button onclick="navigator.clipboard.writeText(document.getElementById('sql').value)">Copy SQL</button>
</body></html>"""

    # Write the compiled HTML page to disk
    with open(path, "w", encoding="utf-8") as f:
        f.write(page)